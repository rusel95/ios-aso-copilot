"""STATE.md is generated from the exported objects, and a hand-written one is never replaced."""
import contextlib
import datetime as dt
import io
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tests.helpers import AS_OF, SAMPLE, copy_store  # noqa: E402

from aso.dashboard import export  # noqa: E402

DAY = dt.date.fromisoformat(AS_OF)
MARKER = "<!-- generated by export_dashboard; do not edit -->"


def text(store=SAMPLE, day=DAY):
    return export.state_md(export.build_all(store, day)[0], day)


def run(store, check_only=False):
    with contextlib.redirect_stdout(io.StringIO()) as said:
        code = export.run(store, DAY, check_only=check_only)
    return code, said.getvalue()


class StateText(unittest.TestCase):
    def test_it_starts_with_the_marker_and_names_the_day(self):
        lines = text().splitlines()
        self.assertEqual(lines[0], MARKER)
        self.assertIn(AS_OF, lines[1])

    def test_the_hypothesis_counts_and_the_due_list(self):
        made = text()
        self.assertIn("2 due", made)
        self.assertIn("- H005 ua tide phrases: window ended 2026-11-03, 11 days past", made)
        self.assertIn("- C001 ", made)
        self.assertNotIn("- H001 ", made)                 # judged: not in the due list

    def test_the_queue_and_the_newest_figures_with_their_period(self):
        made = text()
        self.assertIn("- Q001 2026-10-30 needs a go — create the us penny flight", made)
        self.assertIn("First-time downloads: 64 (week of 2026-11-02)", made)
        # the sweep of 2026-11-09 read two keys of ten: like the page, the headline is the last full sweep (4 of 9)
        self.assertIn("Share in the top 30: 44.4% (read on 2026-11-02)", made)
        self.assertIn("Deletions per 100 installs: 40.0 (week of 2026-11-02)", made)

    def test_each_source_has_its_last_day_or_the_reason_it_has_none(self):
        made = text()
        self.assertIn("| Keyword ranks | 2026-11-09 |", made)
        self.assertIn("| Install lifecycle | week of 2026-11-02 |", made)
        with tempfile.TemporaryDirectory() as tmp:
            store = copy_store(tmp)
            (store / "metrics" / "telemetry.csv").unlink()
            self.assertIn("| In-app | none: no_source |", text(store))

    def test_a_day_is_a_function_of_the_store(self):
        self.assertEqual(text(), text())
        self.assertNotEqual(text(), text(day=dt.date(2026, 11, 5)))
        self.assertTrue(text().endswith("\n") and "\n\n\n" not in text())


class StateFile(unittest.TestCase):
    def test_the_export_writes_it_and_a_second_run_leaves_it(self):
        with tempfile.TemporaryDirectory() as tmp:
            store = copy_store(tmp)
            _, said = run(store)
            self.assertIn("WROTE STATE.md", said)
            self.assertEqual((store / "STATE.md").read_text(encoding="utf-8"), text(store))
            self.assertIn("SAME STATE.md", run(store)[1])

    def test_a_hand_written_one_is_kept(self):
        with tempfile.TemporaryDirectory() as tmp:
            store = copy_store(tmp)
            (store / "STATE.md").write_text("# State\n\nwritten by a person\n", encoding="utf-8")
            code, said = run(store)
            self.assertEqual(code, 0)
            self.assertIn("KEPT STATE.md: written by hand, archive it first", said)
            self.assertEqual((store / "STATE.md").read_text(encoding="utf-8"), "# State\n\nwritten by a person\n")
            self.assertEqual(run(store, check_only=True)[0], 0)       # nor does the check hold it against the store

    def test_the_check_names_a_generated_one_that_went_stale(self):
        with tempfile.TemporaryDirectory() as tmp:
            store = copy_store(tmp)
            run(store)
            self.assertEqual(run(store, check_only=True)[0], 0)
            (store / "STATE.md").write_text(MARKER + "\nedited\n", encoding="utf-8")
            code, said = run(store, check_only=True)
            self.assertEqual((code, said.splitlines()[-1]), (1, "FAIL check: STATE.md"))
            self.assertEqual((store / "STATE.md").read_text(encoding="utf-8"), MARKER + "\nedited\n")   # a check writes nothing


if __name__ == "__main__":
    unittest.main()
