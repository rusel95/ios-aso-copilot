"""STATE.md: one screen of the store's state, written from the exported objects and from nothing else."""
from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

from aso.dashboard.contract import CATALOG, load_catalog

MARKER = "<!-- generated by export_dashboard; do not edit -->"
PLACES = CATALOG.parent / "places.json"
STATES = (("open", "open"), ("due", "due"), ("not-shipped", "not shipped"), ("judged", "judged"))


def shown(value, unit: str) -> str:
    """A figure as the page prints it."""
    if unit == "ratio":
        return f"{value * 100:.1f}%"
    if unit == "usd":
        return f"{'-' if value < 0 else ''}${abs(value):,.2f}"
    if unit == "per_100":
        return f"{value:.1f}"
    if unit == "stars":
        return f"{value:.2f}"
    return f"{value:,}" if isinstance(value, int) else f"{value:.1f}"


def newest(files: dict, kind: str) -> list:
    """The period files of one kind, newest first."""
    return [files[path] for path in sorted((p for p in files if p.startswith(kind + "/")), reverse=True)]


def partial_sweep(file: dict, under: float) -> bool:
    """True for a sweep that read less than the catalog's share of the tracked keys: the page leaves it out of its
    headline too, since a share of a handful of keys says nothing about the basket."""
    figures = file["families"].get("ranks", {}).get("figures", {})
    read, tracked = figures.get("keys_read", {}).get("value"), figures.get("tracked_keys", {}).get("value")
    return bool(tracked) and read is not None and read / tracked < under


def state_md(files: dict, as_of: dt.date) -> str:
    catalog, places = load_catalog()["families"], json.loads(PLACES.read_text(encoding="utf-8"))["overview"]
    hyps = files["hypotheses.json"]["hypotheses"]
    lines = [MARKER, f"# State as of {as_of}", "",
             "Written by the export from `data/`. To change it, change the store and export again.", "",
             "## Hypotheses", "",
             " · ".join(f"{sum(h['state'] == state for h in hyps)} {word}" for state, word in STATES), ""]
    for h in sorted((h for h in hyps if h["state"] == "due"), key=lambda h: (-h["days_past_window"], h["id"])):
        lines.append(f"- {h['id']} {h['title']}: window ended {h['window_end']}, {h['days_past_window']} days past")

    lines += ["", "## Queue", ""]
    lines += [f"- {q['id']} {q['date']} {q['title']}" for q in files["events.json"]["queue"]] or ["Nothing waits for a go."]

    lines += ["", "## Newest figures", ""]
    for key in places:
        name, figure = key.split(".", 1)
        kind, spec = catalog[name]["kind"], catalog[name]["figures"][figure]
        found = next(((f["period"]["id"], f["families"][name]["figures"][figure]) for f in newest(files, kind)
                      if "value" in f["families"].get(name, {}).get("figures", {}).get(figure, {})
                      and not (name == "ranks" and partial_sweep(f, catalog["ranks"]["partial_under"]))), None)
        lines.append(f"- {spec['title']}: " + (f"{shown(found[1]['value'], spec['unit'])} "
                                                f"({'week of' if kind == 'week' else 'read on'} {found[0]})" if found else "not stored"))

    lines += ["", "## Sources", "", "| Source | Newest | Fetched |", "| --- | --- | --- |"]
    for name, family in catalog.items():
        held = [(f["period"]["id"], f["families"][name]) for f in newest(files, family["kind"]) if name in f["families"]]
        there = next(((day, found) for day, found in held if "unavailable" not in found), None)
        if there:
            lines.append(f"| {family['title']} | {'week of ' if family['kind'] == 'week' else ''}{there[0]} | {there[1].get('fetched_at', '')} |")
        else:
            lines.append(f"| {family['title']} | none: {held[0][1]['unavailable']['code'] if held else 'no_source'} | |")
    return "\n".join(lines) + "\n"


def ours(path: Path) -> bool:
    """True when STATE.md may be written: it is absent, or the export wrote it."""
    return not path.is_file() or path.read_text(encoding="utf-8").startswith(MARKER + "\n")
